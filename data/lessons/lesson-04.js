<p>二战前后，理想主义式微，现实主义兴起。汉斯·摩根索在《国家间政治》中提出那句著名的话——"以权力界定利益"。他的意思是：国家利益不能抽象地定义为"善"或"正义"，因为每个国家都宣称自己追求正义；要理解一个国家的利益，必须看它在具体权力关系中的位置与追求。这句话奠定了现实主义分析国家利益的基本方法：从权力格局出发，而非从道德宣言出发。</p>

<p>硬实力擅长"命令"——通过威胁或利诱让他国做本来不愿做的事；软实力擅长"吸引"——让他国自愿想要你所想要的。奈伊强调，在信息时代，软实力的成本更低、效果更持久，因为它依赖的是认同而非强制。但软实力也有局限：它见效慢、难以直接测量，且必须建立在可信度之上——如果一个国家的价值观宣传与其实际行动不符，吸引力会迅速消散。</p>

<li><strong>风险社会改变了威胁性质</strong>：人造的、不可见的、跨国的风险，需要新的治理形式与韧性思维。</li>
<li><strong>参照对象的选择决定政策方向</strong>：国家安全、人类安全与生态安全，会导向完全不同的应对方式。</li>
<li><strong>四类威胁各有特殊难题</strong>：气候难在分配正义、疫情难在协调分配、网络难在归因威慑、反恐难在权利平衡。</li>
<li><strong>治理错配是共同困境</strong>：问题跨国而工具主要是国家的，这与第二十七章的全球治理结论一致。</li>
<li><strong>"威胁倍增器"比"直接威胁"更审慎</strong>：气候与冲突关系是间接、条件性的，过度军事化可能偏离根源。</li>
